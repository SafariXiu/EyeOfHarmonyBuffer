package com.EyeOfHarmonyBuffer.space.talos.biome;

public final class CoastProfile {
    public final int shelfMin, shelfMax;
    public final int beachMin, beachMax;

    public CoastProfile(int shelfMin, int shelfMax, int beachMin, int beachMax) {
        this.shelfMin = shelfMin;
        this.shelfMax = shelfMax;
        this.beachMin = beachMin;
        this.beachMax = beachMax;
    }
}

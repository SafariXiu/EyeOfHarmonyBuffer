package com.EyeOfHarmonyBuffer.space.talos.chunk.river_layer.format;

public final class RiverPoint {
    private final double x;
    private final double z;

    public RiverPoint(double x, double z) {
        this.x = x;
        this.z = z;
    }

    public double getX() {
        return x;
    }

    public double getZ() {
        return z;
    }
}
